// [=] 与 [&] 的对比实验
//   g++ -std=c++20 -Wall -Wextra labs/cpp_capture.cpp -o /tmp/capture && /tmp/capture

#include <cstdio>

// ---------------------------------------------------------------
// 实验 1：[=] 按值捕获所有用到的变量
// ---------------------------------------------------------------
static void demo_copy() {
    std::puts("== demo_copy：[=] 按值 ==");

    int a = 1, b = 2;

    // 这里用到了 a 和 b，[=] 会把它们各拷贝一份存进 lambda
    auto display = [=] { std::printf("lambda 里的副本: a=%d, b=%d\n", a, b); };

    a = 100;
    b = 200;

    display();  // 打印 1 和 2：捕获那一刻就拍好照了
    std::printf("外面的变量:      a=%d, b=%d\n", a, b);
}

// ---------------------------------------------------------------
// 实验 2：[&] 按引用捕获所有用到的变量
// ---------------------------------------------------------------
static void demo_ref() {
    std::puts("\n== demo_ref：[&] 按引用 ==");

    int a = 1, b = 2;

    auto modify = [&] {
        a += 10;  // 直接改外面的 a
        b += 20;  // 直接改外面的 b
    };

    modify();
    std::printf("调用后外面的变量: a=%d, b=%d\n", a, b);  // 11 和 22
}

// ---------------------------------------------------------------
// 实验 3：混合使用
//   [=, &a]  a 按引用，其余按值
//   [&, b]   b 按值，其余按引用
// ---------------------------------------------------------------
static void demo_mixed() {
    std::puts("\n== demo_mixed：混合捕获 ==");

    int a = 1, b = 2;

    auto f = [=, &a] {
        a += 100;  // a 是引用，改的是外面
        return b;  // b 是副本，返回的是捕获时的 2
    };

    b = 200;  // 改外面的 b，不影响 lambda 里的副本
    int result = f();

    std::printf("f() 返回 %d（捕获时的 b），外面的 a=%d，b=%d\n", result, a, b);
}

// ---------------------------------------------------------------
// 实验 4：[=] 不等于"深拷贝"
//   捕获指针时，拷贝的只是指针值，指向的还是同一块内存。
// ---------------------------------------------------------------
static void demo_pointer() {
    std::puts("\n== demo_pointer：[=] 捕获指针 ==");

    int value = 7;
    int* p = &value;

    auto f = [=] {
        *p = 42;  // p 是副本，但副本和原指针指向同一个 value
    };

    f();
    std::printf("value = %d（被 lambda 通过指针改掉了）\n", value);
}

int main() {
    demo_copy();
    demo_ref();
    demo_mixed();
    demo_pointer();
}
